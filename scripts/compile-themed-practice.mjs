import {writeFileSync} from 'node:fs';
import {themedCrossword} from '../themed-crossword.js';
import {random} from '../daily-puzzles.js';
const boards=[],grids=new Set();
for(let index=0;index<100;index++){
 for(let attempt=0;attempt<100;attempt++){
  const board=themedCrossword({hard:index>=50,rng:random('practice-crossword-v6:'+index+':'+attempt)});
  if(grids.has(board.grid))continue;
  boards.push(board);grids.add(board.grid);break;
 }
 if(boards.length!==index+1)throw Error('Missing distinct practice crossword '+index);
}
writeFileSync(new URL('../themed-practice-bank.js',import.meta.url),'// Generated by scripts/compile-themed-practice.mjs. Original themes and clues.\nexport const THEMED_PRACTICE='+JSON.stringify(boards)+';\n');
console.log('Compiled 100 distinct themed practice crosswords.');
