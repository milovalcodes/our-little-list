// Release assembly: gameplay/art sources remain in the companion prototype.
// Pass its folder explicitly on another machine. Generated output is committed
// so Pages and the worker never depend on a developer's local directory.
import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {attachSkillKitchen} from './build-star-kitchen.mjs';
const source=process.argv[2]?resolve(process.argv[2]):fileURLToPath(new URL('../../../outputs/baby-star-demo/',import.meta.url));
const root=new URL('../',import.meta.url);
execFileSync(process.execPath,[resolve(source,'build.mjs')],{stdio:'inherit'});
mkdirSync(new URL('little-star/',root),{recursive:true});
copyFileSync(resolve(source,'star-engine.mjs'),new URL('little-star/engine.mjs',root));
copyFileSync(resolve(source,'star-gameplay.mjs'),new URL('little-star/star-gameplay.mjs',root));
// Keep the actual restore function available to CI's DOM-free regression
// harness. It is generated from the same source as the minified game below.
const ui=readFileSync(resolve(source,'star-ui.js'),'utf8');
const restore=ui.slice(ui.indexOf(' function restore(saved){'),ui.indexOf(" globalThis.addEventListener('openai:set_globals'"));
if(!restore.includes('function restore(saved)'))throw Error('Cannot find the UI restore function.');
mkdirSync(new URL('test/fixtures/',root),{recursive:true});
writeFileSync(new URL('test/fixtures/star-ui-restore.js',root),'// Generated by tools/build-little-star.mjs. Do not edit.\n'+restore);
for(const name of ['star-playroom.js','star-cooking.js'])copyFileSync(resolve(source,name),new URL('test/fixtures/'+name,root));
const touchTests=readFileSync(resolve(source,'star-touch.test.mjs'),'utf8').split("const source=readFileSync(new URL('./star-ui.js'")[0]
 .replace("'./star-gameplay.mjs'","'../little-star/star-gameplay.mjs'").replace("'./star-engine.mjs'","'../little-star/engine.mjs'")
 .replace('new URL(name,import.meta.url)',"new URL('./fixtures/'+name,import.meta.url)");
writeFileSync(new URL('test/star-touch.test.mjs',root),'// Generated controller touch regressions; source: companion star-touch.test.mjs.\n'+touchTests);
let html=readFileSync(resolve(source,'dist/alpha.html'),'utf8');
// Publish the standalone prototype's artwork as immutable files: a small UI
// update must not download the entire wardrobe again.
mkdirSync(new URL('little-star/art/',root),{recursive:true});
const atlases=new Set();
html=html.replace(/data:image\/webp;base64,([A-Za-z0-9+/=]+)/g,(_,encoded)=>{
 const bytes=Buffer.from(encoded,'base64'),hash=createHash('sha256').update(bytes).digest('hex').slice(0,20);
 const path=`little-star/art/${hash}.webp`;
 writeFileSync(new URL(path,root),bytes);atlases.add(path);return path;
});
console.log(`Published ${atlases.size} immutable WebP atlases.`);
const bootstrap=`<script>globalThis.starLive={offline:false};starLive.ready=new Promise(resolve=>{starLive.resolve=resolve;});</script><nav class="star-live-links" aria-label="App links"><a href="activities.html">← Activities</a><a href="phone-check.html">Notifications</a></nav><div id="star-connection" class="star-connection" role="status">Connecting…</div><div id="auth-root"></div><script type="module" src="little-star-live.js"></script>`;
html=html.replace(/<script>[\s\S]*?<\/script>/,()=>bootstrap)
 .replace('<title>Little Star · private alpha</title>','<title>Little Star</title>')
 .replace('</head>','<meta name="theme-color" content="#172b33"><link rel="manifest" href="manifest.webmanifest"><link rel="icon" href="icon-192.png"><link rel="stylesheet" href="little-star-live.css"></head>')
 .replace('<div id="little-star-demo">','<div id="little-star-demo" hidden>')
 .replace('class="prototype-tag">local alpha','class="prototype-tag">alpha')
 .replace('aria-label="Simulated visitor"','aria-label="Signed-in visitor"')
 .replace('aria-label="Little Star: private alpha"','aria-label="Little Star"');
writeFileSync(new URL('little-star.html',root),attachSkillKitchen(html));
console.log('Built live Little Star and shared authoritative engine.');
